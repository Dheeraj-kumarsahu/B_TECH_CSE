#include <stdio.h>
int main (){
    int Num = 12;
    long long int Num1 = 1234567890123456789;
    char cha = 'A';
    float Num2 = 12.34;
    double Num3=1.234456;
    printf("Integer: %d\n", Num);
    printf("Long Long Integer: %lld\n",Num1);
    printf("Character: %c\n", cha);
    printf("Float: %f\n", Num2);
    printf("Double: %lf\n", Num3);
    return 0;
}